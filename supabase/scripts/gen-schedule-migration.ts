// Generates the migration that seeds daily_schedule from src/data/daily.json + src/data/puzzles.json,
// and public.playable_region_ids() from data/regions.json. Never hand-edit the output.
// Usage: npx tsx supabase/scripts/gen-schedule-migration.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { DailySchedule, Puzzle, Region } from '../functions/_shared/engine/types.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
const read = <T>(p: string): T => JSON.parse(readFileSync(root + p, 'utf8')) as T;
const OUT = 'supabase/migrations/20261016000100_seed_daily_schedule.sql';

const daily = read<DailySchedule>('src/data/daily.json');
const puzzlesRaw = read<Puzzle[] | { puzzles: Puzzle[] }>('src/data/puzzles.json');
const puzzles = Array.isArray(puzzlesRaw) ? puzzlesRaw : puzzlesRaw.puzzles;
const regions = read<{ regions: Region[] }>('data/regions.json').regions;

const byId = new Map(puzzles.map((p) => [p.id, p]));
const ID = /^[A-Z]{2}$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;

const rows = daily.entries.map(({ date, puzzleId }) => {
  const p = byId.get(puzzleId);
  if (!p) throw new Error(`daily.json ${date}: unknown puzzle ${puzzleId}`);
  if (!DATE.test(date) || !ID.test(p.start) || !ID.test(p.end) || !/^[A-Z]{2}-[A-Z]{2}$/.test(p.id) || !Number.isInteger(p.k)) {
    throw new Error(`daily.json ${date}: malformed entry`);
  }
  return `  ('${date}', '${p.id}', '${p.start}', '${p.end}', ${p.k})`;
});

const playable = regions.filter((r) => r.playable).map((r) => r.id).sort();
if (!playable.every((id) => ID.test(id))) throw new Error('malformed region id');

const sql = `-- GENERATED by supabase/scripts/gen-schedule-migration.ts from src/data/daily.json (schedule v${daily.version})
-- and data/regions.json. Do not edit by hand. Past dates are never changed: on conflict do nothing.

create or replace function public.playable_region_ids()
returns text[]
language sql
immutable
set search_path = ''
as $$ select array[${playable.map((id) => `'${id}'`).join(',')}]::text[] $$;

revoke all on function public.playable_region_ids() from public, anon, authenticated;

insert into public.daily_schedule (ist_date, puzzle_id, start_id, end_id, k) values
${rows.join(',\n')}
on conflict (ist_date) do nothing;
`;

writeFileSync(root + OUT, sql);
console.log(`${OUT}: ${rows.length} dates (${daily.entries[0]?.date} → ${daily.entries.at(-1)?.date}), ${playable.length} playable ids`);
